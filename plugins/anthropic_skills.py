def _get_output_path(filename: str, default_ext: str) -> Path:
    name = (filename or f"Amatya_Document_{int(time.time())}{default_ext}").strip()
    if not name.endswith(default_ext):
        name += default_ext
    # Resolve to user Desktop if exists, else workspace
    desktop = Path.home() / "Desktop"
    if desktop.is_dir():
        return desktop / Path(name).name
    return BASE_DIR / Path(name).name


def _build_docx(output_path: Path, title: str, content: str, rows: Optional[List[Dict[str, Any]]]) -> str:
    import docx
    from docx.shared import Inches, Pt, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    doc = docx.Document()
    
    # Title
    t_para = doc.add_paragraph()
    t_run = t_para.add_run(title or "Document")
    t_run.font.name = "Arial"
    t_run.font.size = Pt(22)
    t_run.font.bold = True
    t_run.font.color.rgb = RGBColor(0, 102, 204)
    t_para.alignment = WD_ALIGN_PARAGRAPH.LEFT

    # Metadata subtitle
    sub_para = doc.add_paragraph()
    sub_run = sub_para.add_run(f"Generated by AMATYA · {time.strftime('%B %d, %Y')}")
    sub_run.font.name = "Arial"
    sub_run.font.size = Pt(9.5)
    sub_run.font.italic = True
    sub_run.font.color.rgb = RGBColor(128, 128, 128)

    doc.add_paragraph()  # spacer

    # Content paragraphs & headings
    lines = (content or "").split("\n")
    for line in lines:
        sline = line.strip()
        if not sline:
            continue
        if sline.startswith("# "):
            h = doc.add_heading(level=1)
            hrun = h.add_run(sline[2:].strip())
            hrun.font.name = "Arial"
            hrun.font.size = Pt(16)
            hrun.font.color.rgb = RGBColor(0, 102, 204)
        elif sline.startswith("## "):
            h = doc.add_heading(level=2)
            hrun = h.add_run(sline[3:].strip())
            hrun.font.name = "Arial"
            hrun.font.size = Pt(13)
            hrun.font.color.rgb = RGBColor(51, 51, 51)
        elif sline.startswith("- ") or sline.startswith("* ") or sline.startswith("• "):
            p = doc.add_paragraph(style="List Bullet")
            prun = p.add_run(sline.lstrip("-*• ").strip())
            prun.font.name = "Arial"
            prun.font.size = Pt(11)
        else:
            p = doc.add_paragraph()
            prun = p.add_run(sline)
            prun.font.name = "Arial"
            prun.font.size = Pt(11)

    # Optional table
    if rows and isinstance(rows, list) and len(rows) > 0 and isinstance(rows[0], dict):
        headers = list(rows[0].keys())
        table = doc.add_table(rows=len(rows) + 1, cols=len(headers))
        table.style = "Table Grid"

        # Format header row
        hdr_cells = table.rows[0].cells
        for idx, h_text in enumerate(headers):
            hdr_cells[idx].text = str(h_text).capitalize()
            p = hdr_cells[idx].paragraphs[0]
            for r in p.runs:
                r.font.bold = True
                r.font.color.rgb = RGBColor(255, 255, 255)
            # Background shading
            from docx.oxml import OxmlElement
            from docx.oxml.ns import qn
            tcPr = hdr_cells[idx]._tc.get_or_add_tcPr()
            shd = OxmlElement('w:shd')
            shd.set(qn('w:val'), 'clear')
            shd.set(qn('w:color'), 'auto')
            shd.set(qn('w:fill'), '0066CC')
            tcPr.append(shd)

        # Populate rows
        for r_idx, row_dict in enumerate(rows):
            row_cells = table.rows[r_idx + 1].cells
            for c_idx, h_text in enumerate(headers):
                row_cells[c_idx].text = str(row_dict.get(h_text, ""))
                p = row_cells[c_idx].paragraphs[0]
                p.runs[0].font.name = "Arial"
                p.runs[0].font.size = Pt(10)

    doc.save(str(output_path))
    return str(output_path)


def _build_xlsx(output_path: Path, title: str, rows: Optional[List[Dict[str, Any]]]) -> str:
    import openpyxl
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    from openpyxl.utils import get_column_letter

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = (title or "Summary")[:31]

    # Title block
    ws["A1"] = title or "Dataset Summary"
    ws["A1"].font = Font(name="Segoe UI", size=16, bold=True, color="003366")
    ws["A2"] = f"Generated by AMATYA · {time.strftime('%Y-%m-%d %H:%M:%S')}"
    ws["A2"].font = Font(name="Segoe UI", size=9, italic=True, color="666666")

    start_row = 4
    if rows and isinstance(rows, list) and len(rows) > 0 and isinstance(rows[0], dict):
        headers = list(rows[0].keys())
        hdr_fill = PatternFill(start_color="005BB5", end_color="005BB5", fill_type="solid")
        hdr_font = Font(name="Segoe UI", size=11, bold=True, color="FFFFFF")
        thin_border = Border(
            left=Side(style="thin", color="CCCCCC"),
            right=Side(style="thin", color="CCCCCC"),
            top=Side(style="thin", color="CCCCCC"),
            bottom=Side(style="thin", color="CCCCCC"),
        )

        for col_idx, h_name in enumerate(headers, 1):
            cell = ws.cell(row=start_row, column=col_idx, value=str(h_name).title())
            cell.fill = hdr_fill
            cell.font = hdr_font
            cell.alignment = Alignment(horizontal="center", vertical="center")
            cell.border = thin_border

        alt_fill = PatternFill(start_color="F5F8FC", end_color="F5F8FC", fill_type="solid")
        for r_offset, r_data in enumerate(rows, 1):
            curr_row = start_row + r_offset
            for col_idx, h_name in enumerate(headers, 1):
                val = r_data.get(h_name, "")
                cell = ws.cell(row=curr_row, column=col_idx, value=val)
                cell.font = Font(name="Segoe UI", size=10)
                cell.border = thin_border
                if r_offset % 2 == 0:
                    cell.fill = alt_fill

        # Auto-fit column widths
        for col in ws.columns:
            max_len = max(len(str(cell.value or "")) for cell in col)
            col_letter = get_column_letter(col[0].column)
            ws.column_dimensions[col_letter].width = max(max_len + 4, 12)
    else:
        ws["A4"] = "No tabular data provided."

    wb.save(str(output_path))
    return str(output_path)


def _build_pptx(output_path: Path, title: str, content: str) -> str:
    import pptx
    from pptx.util import Inches, Pt
    from pptx.dml.color import RGBColor

    prs = pptx.Presentation()
    prs.slide_width = Inches(13.333)  # 16:9 widescreen
    prs.slide_height = Inches(7.5)

    blank_layout = prs.slide_layouts[6]

    # Slide 1: Title Slide
    s1 = prs.slides.add_slide(blank_layout)
    # Background shape
    bg = s1.shapes.add_shape(pptx.enum.shapes.MSO_SHAPE.RECTANGLE, 0, 0, Inches(13.333), Inches(7.5))
    bg.fill.solid()
    bg.fill.fore_color.rgb = RGBColor(10, 25, 47)  # Navy slate
    bg.line.fill.background()

    # Title box
    tb = s1.shapes.add_textbox(Inches(1.5), Inches(2.5), Inches(10.333), Inches(2.5))
    tf = tb.text_frame
    p1 = tf.paragraphs[0]
    p1.text = title or "Executive Presentation"
    p1.font.name = "Arial"
    p1.font.size = Pt(40)
    p1.font.bold = True
    p1.font.color.rgb = RGBColor(255, 255, 255)

    p2 = tf.add_paragraph()
    p2.text = f"Prepared by AMATYA Systems · {time.strftime('%B %d, %Y')}"
    p2.font.name = "Arial"
    p2.font.size = Pt(16)
    p2.font.color.rgb = RGBColor(0, 204, 255)

    # Content slides split by double newline or sections
    sections = [s.strip() for s in (content or "").split("\n\n") if s.strip()]
    if not sections:
        sections = ["Executive Summary", "Key Objectives & Milestones", "Strategic Next Steps"]

    for idx, sec in enumerate(sections[:6], 2):
        slide = prs.slides.add_slide(blank_layout)
        # Header banner
        hbar = slide.shapes.add_shape(pptx.enum.shapes.MSO_SHAPE.RECTANGLE, 0, 0, Inches(13.333), Inches(1.2))
        hbar.fill.solid()
        hbar.fill.fore_color.rgb = RGBColor(15, 35, 60)
        hbar.line.fill.background()

        htext = slide.shapes.add_textbox(Inches(0.8), Inches(0.2), Inches(11.0), Inches(0.8))
        hp = htext.text_frame.paragraphs[0]
        sec_lines = sec.split("\n")
        hp.text = sec_lines[0].lstrip("#-•* ")
        hp.font.name = "Arial"
        hp.font.size = Pt(24)
        hp.font.bold = True
        hp.font.color.rgb = RGBColor(0, 204, 255)

        # Body card
        card = slide.shapes.add_shape(pptx.enum.shapes.MSO_SHAPE.ROUNDED_RECTANGLE, Inches(0.8), Inches(1.6), Inches(11.733), Inches(5.2))
        card.fill.solid()
        card.fill.fore_color.rgb = RGBColor(245, 248, 252)
        card.line.color.rgb = RGBColor(210, 225, 245)

        btext = slide.shapes.add_textbox(Inches(1.2), Inches(1.9), Inches(10.9), Inches(4.6))
        btf = btext.text_frame
        btf.word_wrap = True

        bullet_lines = sec_lines[1:] if len(sec_lines) > 1 else ["Key metric and operational finding analysis.", "Strategic milestone progress aligned with system goals."]
        for b_idx, bline in enumerate(bullet_lines):
            bp = btf.paragraphs[0] if b_idx == 0 else btf.add_paragraph()
            bp.text = bline.lstrip("-•* ")
            bp.font.name = "Arial"
            bp.font.size = Pt(16)
            bp.font.color.rgb = RGBColor(40, 45, 55)

    prs.save(str(output_path))
    return str(output_path)


