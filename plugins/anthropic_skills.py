def run(parameters: dict, player=None, session_memory=None) -> str:
    """Execute Anthropic document & artifact skills."""
    action = str(parameters.get("action") or "list_skills").strip().lower()
    filename = parameters.get("filename")
    title = parameters.get("title") or "AMATYA Intelligence Document"
    content = parameters.get("content") or "Document created with Anthropic skills architecture."
    rows = parameters.get("rows")

    if action == "list_skills":
        skills = []
        if SKILLS_DIR.is_dir():
            skills = [p.name for p in SKILLS_DIR.iterdir() if p.is_dir() and not p.name.startswith(".")]
        res = f"Active integrated Anthropic skills: {', '.join(sorted(skills))}."
        if player is not None:
            try:
                player.show_content("Anthropic Skills Suite", f"# 🛠️ Integrated Skills\n\n- " + "\n- ".join(sorted(skills)))
            except Exception:
                pass
        return res

    try:
        if action == "create_docx":
            out_path = _get_output_path(filename or f"{title.replace(' ', '_')}.docx", ".docx")
            saved = _build_docx(out_path, title, content, rows)
            msg = f"Word document '{out_path.name}' successfully generated at {saved}."
            if player is not None:
                try:
                    player.show_content(f"Document Created: {out_path.name}", f"# 📄 {title}\n\n**Path:** `{saved}`\n\n{content}")
                    player.write_log(f"DOCX: Generated {out_path.name}")
                except Exception:
                    pass
            return f"I have created the Word document '{out_path.name}' on your desktop."

        elif action == "create_xlsx":
            out_path = _get_output_path(filename or f"{title.replace(' ', '_')}.xlsx", ".xlsx")
            saved = _build_xlsx(out_path, title, rows)
            msg = f"Excel spreadsheet '{out_path.name}' successfully generated at {saved}."
            if player is not None:
                try:
                    player.show_content(f"Spreadsheet Created: {out_path.name}", f"# 📊 {title}\n\n**Path:** `{saved}`\n\nTotal rows: {len(rows) if rows else 0}")
                    player.write_log(f"XLSX: Generated {out_path.name}")
                except Exception:
                    pass
            return f"I have generated the Excel spreadsheet '{out_path.name}' on your desktop."

        elif action == "create_pptx":
            out_path = _get_output_path(filename or f"{title.replace(' ', '_')}.pptx", ".pptx")
            saved = _build_pptx(out_path, title, content)
            msg = f"PowerPoint presentation '{out_path.name}' successfully generated at {saved}."
            if player is not None:
                try:
                    player.show_content(f"Slide Deck Created: {out_path.name}", f"# 📽️ {title}\n\n**Path:** `{saved}`\n\n{content}")
                    player.write_log(f"PPTX: Generated {out_path.name}")
                except Exception:
                    pass
            return f"I have built the presentation deck '{out_path.name}' on your desktop."

        elif action == "create_web_artifact":
            out_path = _get_output_path(filename or f"{title.replace(' ', '_')}.html", ".html")
            saved = _build_web_artifact(out_path, title, content)
            if player is not None:
                try:
                    player.show_content(f"Artifact Created: {out_path.name}", f"# 🌐 {title}\n\n**Path:** `{saved}`")
                    player.write_log(f"ARTIFACT: Generated {out_path.name}")
                except Exception:
                    pass
            return f"I have created the interactive web artifact '{out_path.name}' on your desktop."

        return f"Unknown document action '{action}'."

    except Exception as e:
        return f"Could not complete {action}: {e}"
